/** A live fact from LIVE_TR: day strings become "am Sonntag, 25. Oktober" and so on. */
function live_tr(string $lang, string $key, array $v): array {
    $r = [];
    foreach ($v as $k => $x) $r['{' . $k . '}'] = in_array($k, ['eu', 'us', 'day'], true) ? lang_on_day($lang, $x) : (string)$x;
    if (isset($v['gap'])) $r['{gap_h}'] = lang_amount($lang, $v['gap'] . ' hours');
    return ['kind' => 'live', 'href' => fact_link('dst', $lang), 'text' => strtr(LIVE_TR[$lang][$key], $r)];
}

/** A fact's text in the language: English, Chinese, or from FACTS_TR (English when missing). */
function fact_text(int $i, string $lang): string {
    $f = FACTS[$i];
    if ($lang === 'zh') return $f[2];
    return FACTS_TR[$lang][$i] ?? $f[1];
}
